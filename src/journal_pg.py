"""
The trade journal, on Postgres.

A port of TradeJournal, not a redesign. Every method returns what the
SQLite one returns, for the same inputs, because the whole migration is
only safe if the two are interchangeable — tests/test_journal_parity.py
runs both side by side and compares.

Three things are deliberately kept as they are rather than modernised:

* Timestamps stay TEXT. start_of_day_equity() matches the day with
  substr(ts,1,10) on an ISO string; a real timestamp type would be
  reinterpreted against a server timezone and could shift which readings
  count as "today". That number is what the daily-loss circuit breaker
  measures against, so it is the last thing to change casually.
* risk_approved stays an integer 0/1 rather than a boolean, so the dicts
  handed back to the rest of the bot are identical.
* The SQL keeps SQLite's shapes (the nested select in equity_curve, the
  ORDER BY in closed_trades) so a difference in results means a real
  difference, not a rewrite.

The tables live in a `trading` schema rather than `public`: Supabase
exposes public over PostgREST, and this data has no business being
reachable over HTTP.
"""
from __future__ import annotations

import csv
import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Optional

import psycopg
from psycopg.rows import dict_row

from src.logging_setup import get_logger
from src.models import OrderResult, RiskDecision, Signal

log = get_logger(__name__)

SCHEMA_NAME = "trading"

SCHEMA = f"""
CREATE SCHEMA IF NOT EXISTS {SCHEMA_NAME};

CREATE TABLE IF NOT EXISTS {SCHEMA_NAME}.signals (
    id              text PRIMARY KEY,
    created_at      text NOT NULL,
    symbol          text NOT NULL,
    source          text,
    timeframe       text,
    direction       text,
    entry           double precision,
    stop            double precision,
    target          double precision,
    risk_reward     double precision,
    confidence      double precision,
    reasoning       text,
    invalidation    text,
    risk_notes      text,
    news_impact     text,
    risk_approved   integer,
    risk_reason     text,
    shares          double precision,
    dollar_risk     double precision,
    account_risk_pct double precision,
    status          text NOT NULL,
    extra           text
);

CREATE TABLE IF NOT EXISTS {SCHEMA_NAME}.orders (
    id              text PRIMARY KEY,
    signal_id       text REFERENCES {SCHEMA_NAME}.signals(id),
    created_at      text NOT NULL,
    broker          text,
    broker_order_id text,
    symbol          text,
    side            text,
    qty             double precision,
    status          text,
    message         text,
    raw             text
);

CREATE TABLE IF NOT EXISTS {SCHEMA_NAME}.trades (
    id          text PRIMARY KEY,
    signal_id   text REFERENCES {SCHEMA_NAME}.signals(id),
    symbol      text NOT NULL,
    direction   text,
    strategy    text,
    opened_at   text,
    closed_at   text,
    qty         double precision,
    entry       double precision,
    exit        double precision,
    stop        double precision,
    target      double precision,
    pnl         double precision,
    r_multiple  double precision,
    fees        double precision,
    status      text NOT NULL,
    exit_reason text,
    review      text
);

CREATE TABLE IF NOT EXISTS {SCHEMA_NAME}.equity (
    ts       text PRIMARY KEY,
    equity   double precision,
    cash     double precision,
    exposure double precision
);

CREATE TABLE IF NOT EXISTS {SCHEMA_NAME}.runs (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at  text,
    finished_at text,
    scanned     integer,
    signals     integer,
    approved    integer,
    errors      integer,
    notes       text
);

CREATE INDEX IF NOT EXISTS idx_signals_created ON {SCHEMA_NAME}.signals(created_at);
CREATE INDEX IF NOT EXISTS idx_signals_status  ON {SCHEMA_NAME}.signals(status);
CREATE INDEX IF NOT EXISTS idx_trades_status   ON {SCHEMA_NAME}.trades(status);
CREATE INDEX IF NOT EXISTS idx_trades_closed   ON {SCHEMA_NAME}.trades(closed_at);
CREATE INDEX IF NOT EXISTS idx_equity_day ON {SCHEMA_NAME}.equity(substr(ts, 1, 10));
"""


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


class PostgresJournal:
    """Same surface as TradeJournal, backed by Postgres."""

    def __init__(self, dsn: str, *, ensure_schema: bool = True) -> None:
        self.dsn = dsn
        # autocommit because the SQLite journal commits after every write
        # and callers rely on a write being durable the moment it returns.
        # A trade recorded but not committed, then lost to a crash, is the
        # bot and the broker disagreeing about what is open.
        self.conn = psycopg.connect(dsn, autocommit=True, row_factory=dict_row)
        self.conn.execute(f"SET search_path TO {SCHEMA_NAME}, public")
        if ensure_schema:
            self.conn.execute(SCHEMA)

    def close(self) -> None:
        if not self.conn.closed:
            self.conn.close()

    def _all(self, sql: str, params: tuple = ()) -> list[dict]:
        with self.conn.cursor() as cur:
            cur.execute(sql, params)
            return [dict(r) for r in cur.fetchall()]

    def _one(self, sql: str, params: tuple = ()) -> Optional[dict]:
        rows = self._all(sql, params)
        return rows[0] if rows else None

    def _exec(self, sql: str, params: tuple = ()) -> None:
        with self.conn.cursor() as cur:
            cur.execute(sql, params)

    # ------------------------------------------------------------------ #
    # Signals
    # ------------------------------------------------------------------ #
    def log_signal(
        self,
        signal: Signal,
        decision: RiskDecision,
        status: str,
        extra: Optional[dict[str, Any]] = None,
    ) -> None:
        sizing = decision.sizing
        self._exec(
            """INSERT INTO signals VALUES
               (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)
               ON CONFLICT (id) DO UPDATE SET
                 created_at=EXCLUDED.created_at, symbol=EXCLUDED.symbol,
                 source=EXCLUDED.source, timeframe=EXCLUDED.timeframe,
                 direction=EXCLUDED.direction, entry=EXCLUDED.entry,
                 stop=EXCLUDED.stop, target=EXCLUDED.target,
                 risk_reward=EXCLUDED.risk_reward, confidence=EXCLUDED.confidence,
                 reasoning=EXCLUDED.reasoning, invalidation=EXCLUDED.invalidation,
                 risk_notes=EXCLUDED.risk_notes, news_impact=EXCLUDED.news_impact,
                 risk_approved=EXCLUDED.risk_approved, risk_reason=EXCLUDED.risk_reason,
                 shares=EXCLUDED.shares, dollar_risk=EXCLUDED.dollar_risk,
                 account_risk_pct=EXCLUDED.account_risk_pct,
                 status=EXCLUDED.status, extra=EXCLUDED.extra""",
            (
                signal.id,
                signal.created_at.isoformat(),
                signal.symbol,
                signal.source,
                signal.timeframe,
                signal.direction,
                signal.entry,
                signal.stop,
                signal.target,
                round(signal.risk_reward, 3),
                signal.confidence,
                signal.reasoning,
                json.dumps(signal.invalidation),
                signal.risk_notes,
                signal.news_impact,
                int(decision.approved),
                decision.reason,
                sizing.shares if sizing else 0.0,
                sizing.dollar_risk if sizing else 0.0,
                sizing.account_risk_pct if sizing else 0.0,
                status,
                json.dumps(extra or {}),
            ),
        )

    def update_signal_status(self, signal_id: str, status: str) -> None:
        self._exec("UPDATE signals SET status = %s WHERE id = %s", (status, signal_id))

    def get_signal(self, signal_id: str) -> Optional[dict]:
        return self._one("SELECT * FROM signals WHERE id = %s", (signal_id,))

    def recent_signals(self, limit: int = 50) -> list[dict]:
        return self._all(
            "SELECT * FROM signals ORDER BY created_at DESC LIMIT %s", (limit,)
        )

    def signals_since(self, iso_ts: str) -> list[dict]:
        return self._all(
            "SELECT * FROM signals WHERE created_at >= %s ORDER BY created_at",
            (iso_ts,),
        )

    # ------------------------------------------------------------------ #
    # Orders and trades
    # ------------------------------------------------------------------ #
    def log_order(self, order: OrderResult, signal_id: str) -> None:
        self._exec(
            """INSERT INTO orders VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)
               ON CONFLICT (id) DO UPDATE SET
                 signal_id=EXCLUDED.signal_id, created_at=EXCLUDED.created_at,
                 broker=EXCLUDED.broker, broker_order_id=EXCLUDED.broker_order_id,
                 symbol=EXCLUDED.symbol, side=EXCLUDED.side, qty=EXCLUDED.qty,
                 status=EXCLUDED.status, message=EXCLUDED.message, raw=EXCLUDED.raw""",
            (
                order.id,
                signal_id,
                _now(),
                order.broker,
                order.broker_order_id,
                order.symbol,
                order.side,
                order.qty,
                order.status or ("accepted" if order.accepted else "rejected"),
                order.message,
                json.dumps(order.raw)[:4000],
            ),
        )

    def open_trade(self, signal: Signal, qty: float, strategy: str = "") -> str:
        trade_id = f"trd_{signal.id.split('_', 1)[-1]}"
        self._exec(
            """INSERT INTO trades
               (id, signal_id, symbol, direction, strategy, opened_at, closed_at,
                qty, entry, exit, stop, target, pnl, r_multiple, fees, status,
                exit_reason, review)
               VALUES (%s,%s,%s,%s,%s,%s,NULL,%s,%s,NULL,%s,%s,NULL,NULL,0,'open',NULL,NULL)
               ON CONFLICT (id) DO UPDATE SET
                 signal_id=EXCLUDED.signal_id, symbol=EXCLUDED.symbol,
                 direction=EXCLUDED.direction, strategy=EXCLUDED.strategy,
                 opened_at=EXCLUDED.opened_at, closed_at=NULL, qty=EXCLUDED.qty,
                 entry=EXCLUDED.entry, exit=NULL, stop=EXCLUDED.stop,
                 target=EXCLUDED.target, pnl=NULL, r_multiple=NULL, fees=0,
                 status='open', exit_reason=NULL, review=NULL""",
            (
                trade_id,
                signal.id,
                signal.symbol,
                signal.direction,
                strategy or signal.source,
                _now(),
                qty,
                signal.entry,
                signal.stop,
                signal.target,
            ),
        )
        return trade_id

    def close_trade(
        self,
        trade_id: str,
        exit_price: float,
        exit_reason: str = "",
        fees: float = 0.0,
        closed_at: Optional[str] = None,
    ) -> Optional[dict]:
        row = self._one("SELECT * FROM trades WHERE id = %s", (trade_id,))
        if row is None:
            log.warning("journal.close_unknown_trade", trade_id=trade_id)
            return None

        entry, stop, qty = row["entry"], row["stop"], row["qty"]
        direction = row["direction"]
        pnl = (exit_price - entry) * qty if direction == "long" else (entry - exit_price) * qty
        pnl -= fees
        risk_per_share = abs(entry - stop)
        # R-multiple: profit measured in units of the risk actually taken. The
        # only P&L number that is comparable across position sizes.
        r_multiple = (pnl / (risk_per_share * abs(qty))) if risk_per_share and qty else 0.0

        self._exec(
            """UPDATE trades SET closed_at=%s, exit=%s, pnl=%s, r_multiple=%s, fees=%s,
                                 status='closed', exit_reason=%s WHERE id=%s""",
            (closed_at or _now(), exit_price, pnl, r_multiple, fees, exit_reason, trade_id),
        )
        log.info("journal.trade_closed", trade_id=trade_id, pnl=round(pnl, 2),
                 r=round(r_multiple, 2), reason=exit_reason)
        return self.get_trade(trade_id)

    def get_trade(self, trade_id: str) -> Optional[dict]:
        return self._one("SELECT * FROM trades WHERE id = %s", (trade_id,))

    def open_trades(self) -> list[dict]:
        return self._all("SELECT * FROM trades WHERE status = 'open'")

    def closed_trades(self, limit: int = 500, strategy: str | None = None) -> list[dict]:
        if strategy:
            return self._all(
                """SELECT * FROM trades WHERE status='closed' AND strategy=%s
                   ORDER BY closed_at DESC LIMIT %s""",
                (strategy, limit),
            )
        return self._all(
            "SELECT * FROM trades WHERE status='closed' ORDER BY closed_at DESC LIMIT %s",
            (limit,),
        )

    def open_stops(self) -> dict[str, float]:
        """symbol -> stop price, for open-risk accounting."""
        rows = self._all("SELECT symbol, stop FROM trades WHERE status='open'")
        return {r["symbol"]: r["stop"] for r in rows if r["stop"]}

    def save_review(self, trade_id: str, review: str) -> None:
        self._exec("UPDATE trades SET review = %s WHERE id = %s", (review, trade_id))

    # ------------------------------------------------------------------ #
    # Equity and runs
    # ------------------------------------------------------------------ #
    def record_equity(self, equity: float, cash: float, exposure: float) -> None:
        # SQLite's INSERT OR REPLACE. Two readings in the same microsecond
        # collapse to one, exactly as they do there.
        self._exec(
            """
            INSERT INTO equity (ts, equity, cash, exposure) VALUES (%s,%s,%s,%s)
            ON CONFLICT (ts) DO UPDATE
               SET equity = EXCLUDED.equity,
                   cash = EXCLUDED.cash,
                   exposure = EXCLUDED.exposure
            """,
            (_now(), equity, cash, exposure),
        )

    def start_of_day_equity(self, on_date: str | None = None) -> float | None:
        """
        The first equity reading recorded today, or None if there isn't one.

        The number the daily loss limit measures against. Without it the
        limit silently reads 0% every day and never fires, which is the
        worst possible failure for a circuit breaker — it looks like it is
        working.
        """
        day = on_date or _now()[:10]
        row = self._one(
            "SELECT equity FROM equity WHERE substr(ts,1,10) = %s ORDER BY ts LIMIT 1",
            (day,),
        )
        return float(row["equity"]) if row else None

    def equity_curve(self, limit: int = 1000) -> list[dict]:
        return self._all(
            "SELECT * FROM (SELECT * FROM equity ORDER BY ts DESC LIMIT %s) q ORDER BY ts",
            (limit,),
        )

    def start_run(self) -> int:
        row = self._one(
            """INSERT INTO runs (started_at, scanned, signals, approved, errors)
               VALUES (%s,0,0,0,0) RETURNING id""",
            (_now(),),
        )
        return int(row["id"])

    def finish_run(
        self, run_id: int, scanned: int, signals: int, approved: int, errors: int, notes: str = ""
    ) -> None:
        self._exec(
            """UPDATE runs SET finished_at=%s, scanned=%s, signals=%s, approved=%s,
                               errors=%s, notes=%s WHERE id=%s""",
            (_now(), scanned, signals, approved, errors, notes, run_id),
        )

    # ------------------------------------------------------------------ #
    def export_csv(self, destination: Path) -> Path:
        trades = self.closed_trades(limit=100_000)
        destination.parent.mkdir(parents=True, exist_ok=True)
        fields = [
            "id", "symbol", "direction", "strategy", "opened_at", "closed_at",
            "qty", "entry", "exit", "stop", "target", "pnl", "r_multiple",
            "fees", "exit_reason",
        ]
        with destination.open("w", newline="", encoding="utf-8") as fh:
            writer = csv.DictWriter(fh, fieldnames=fields, extrasaction="ignore")
            writer.writeheader()
            writer.writerows(trades)
        log.info("journal.exported", path=str(destination), rows=len(trades))
        return destination
